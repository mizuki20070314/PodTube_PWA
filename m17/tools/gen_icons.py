#!/usr/bin/env python3
"""PWA の Material アイコン(24x24 の SVG パス)を、M17 アプリ用の PNG アトラス(白+アルファ)にする。

入力: podtube-pwa/pwa/web/js/01-icons.js の `var P = {...}`
出力: app/data/icons_<size>.png(サイズごとのアトラス)と app/data/icons.lua(名前→番号)
パスは fontTools の svgLib で読み(円弧も含む)、曲線を折れ線にして、8倍で塗って縮小する(偶奇規則)。
"""
import json, math, os, re

import numpy as np
from fontTools.svgLib.path import parse_path
from fontTools.pens.basePen import BasePen
from PIL import Image, ImageDraw

PWA = r"C:\Users\Mizuki\podtube-pwa\pwa\web\js\01-icons.js"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "data")
SIZES = [14, 16, 20, 24, 32, 48]
COLS = 16
SS = 8  # supersampling


class Flatten(BasePen):
    def __init__(self):
        super().__init__(None)
        self.contours = []
        self.cur = None

    def _moveTo(self, p):
        self.cur = [p]

    def _lineTo(self, p):
        self.cur.append(p)

    def _curveToOne(self, p1, p2, p3):
        p0 = self.cur[-1]
        n = 14
        for i in range(1, n + 1):
            t = i / n
            mt = 1 - t
            x = mt ** 3 * p0[0] + 3 * mt * mt * t * p1[0] + 3 * mt * t * t * p2[0] + t ** 3 * p3[0]
            y = mt ** 3 * p0[1] + 3 * mt * mt * t * p1[1] + 3 * mt * t * t * p2[1] + t ** 3 * p3[1]
            self.cur.append((x, y))

    def _qCurveToOne(self, p1, p2):
        p0 = self.cur[-1]
        n = 10
        for i in range(1, n + 1):
            t = i / n
            mt = 1 - t
            self.cur.append((mt * mt * p0[0] + 2 * mt * t * p1[0] + t * t * p2[0],
                             mt * mt * p0[1] + 2 * mt * t * p1[1] + t * t * p2[1]))

    def _closePath(self):
        if self.cur and len(self.cur) > 2:
            self.contours.append(self.cur)
        self.cur = None

    def _endPath(self):
        self._closePath()


def render(path, size):
    pen = Flatten()
    parse_path(path, pen)
    big = size * SS
    scale = big / 24.0
    acc = np.zeros((big, big), dtype=np.uint8)
    for c in pen.contours:
        im = Image.new("L", (big, big), 0)
        ImageDraw.Draw(im).polygon([(x * scale, y * scale) for x, y in c], fill=1)
        acc ^= np.asarray(im, dtype=np.uint8)  # 偶奇規則: 穴は XOR で抜ける
    a = acc.astype(np.float32).reshape(size, SS, size, SS).mean(axis=(1, 3))
    return (a * 255 + 0.5).astype(np.uint8)


def main():
    src = open(PWA, encoding="utf-8").read()
    i = src.index("var P = {") + len("var P = ")
    depth, j = 0, i
    while True:
        c = src[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    paths = json.loads(src[i:j + 1])
    # the Shorts glyph is drawn by the original app itself (01-icons.js: SHORTS / SHORTS_OUTLINE)
    paths["shorts"] = "M9.5 2.5h5a4 4 0 0 1 4 4v11a4 4 0 0 1-4 4h-5a4 4 0 0 1-4-4v-11a4 4 0 0 1 4-4zM10 8.5v7l6-3.5z"
    paths["shorts_outline"] = ("M9.5 2.5h5a4 4 0 0 1 4 4v11a4 4 0 0 1-4 4h-5a4 4 0 0 1-4-4v-11a4 4 0 0 1 4-4z"
                               "M9.5 4.5h5a2 2 0 0 1 2 2v11a2 2 0 0 1-2 2h-5a2 2 0 0 1-2-2v-11a2 2 0 0 1 2-2z"
                               "M10 8.5v7l6-3.5z")
    names = sorted(paths)
    rows = (len(names) + COLS - 1) // COLS
    for size in SIZES:
        sheet = np.zeros((rows * size, COLS * size, 4), dtype=np.uint8)
        sheet[:, :, :3] = 255
        for k, name in enumerate(names):
            a = render(paths[name], size)
            r, c = divmod(k, COLS)
            sheet[r * size:(r + 1) * size, c * size:(c + 1) * size, 3] = a
        Image.fromarray(sheet, "RGBA").save(os.path.join(OUT, "icons_%d.png" % size), optimize=True)
    lines = ["-- generated by tools/gen_icons.py (Material Icons, Apache-2.0)", "return {",
             "  cols = %d," % COLS, "  sizes = {%s}," % ", ".join(str(s) for s in SIZES), "  names = {"]
    for k, n in enumerate(names):
        lines.append('    ["%s"] = %d,' % (n, k))
    lines += ["  },", "}"]
    open(os.path.join(OUT, "icons.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("icons:", len(names), "sizes:", SIZES, "->", OUT)


if __name__ == "__main__":
    main()
