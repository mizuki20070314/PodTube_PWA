#!/usr/bin/env python3
"""PWA の文言(ja/en)を M17 アプリ用の Lua テーブルに変換する。
入力: podtube-pwa/pwa/web/js/02-i18n.js(JSON風) と 02b-i18n-extra.js(JS風)
出力: app/data/strings.lua   return { ["tab.home"] = {"ホーム","Home"}, ... }
"""
import json, os, re

PWA = r"C:\Users\Mizuki\podtube-pwa\pwa\web\js"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "app", "data", "strings.lua")

Q = r"""('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")"""
EXTRA = re.compile(r"'([A-Za-z0-9_.]+)'\s*:\s*\[\s*" + Q + r"\s*,\s*" + Q + r"\s*\]")


def lua_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    return '"' + s + '"'


def unquote(q):
    body = q[1:-1]
    return re.sub(r"\\(.)", lambda mm: {"n": "\n"}.get(mm.group(1), mm.group(1)), body)


def main():
    src = open(os.path.join(PWA, "02-i18n.js"), encoding="utf-8").read()
    i = src.index("PT.L10N = {") + len("PT.L10N = ")
    depth, j = 0, i
    while True:
        c = src[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    d = json.loads(src[i:j + 1])
    ex = open(os.path.join(PWA, "02b-i18n-extra.js"), encoding="utf-8").read()
    n_extra = 0
    for m in EXTRA.finditer(ex):
        d.setdefault(m.group(1), [unquote(m.group(2)), unquote(m.group(3))])
        n_extra += 1
    lines = ["-- generated by tools/gen_strings.py from the PodTube PWA (ja, en)", "return {"]
    for k in sorted(d):
        lines.append("  [%s] = {%s, %s}," % (lua_str(k), lua_str(d[k][0]), lua_str(d[k][1])))
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("strings:", len(d), "(extra parsed %d)" % n_extra, "->", OUT)


if __name__ == "__main__":
    main()
